/* ------------------------------------------------------------------ */

void flux_effect_reset(flux_device *d) {
    if (!d)
        return;
    flux_platform_mutex_lock(&d->module_state_lock);
    effect_state *st = d->effect_state;
    flux_platform_mutex_unlock(&d->module_state_lock);
    if (!st)
        return;
    flux_platform_mutex_lock(&st->lock);
    for (output_entry *o = st->outputs; o; o = o->next)
        o->leased = false;
    for (intermediate_entry *e = st->intermediates; e; e = e->next)
        e->leased = false;
    flux_platform_mutex_unlock(&st->lock);
}
