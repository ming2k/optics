/*  Reusable frame-slot realtime blur                                 */
/* ------------------------------------------------------------------ */

flux_result flux_blur_filter_create(flux_device *device, flux_blur_filter **out) {
    if (!device || !out)
        return FLUX_ERROR_INVALID_ARGUMENT;
    *out = nullptr;
    flux_blur_filter *filter = flux_internal_alloc(device, sizeof(*filter));
    if (!filter)
        return FLUX_ERROR_OUT_OF_MEMORY;
    atomic_init(&filter->ref_count, 1u);
    filter->device = flux_device_retain(device);
    *out = filter;
    return FLUX_OK;
}

flux_blur_filter *flux_blur_filter_retain(flux_blur_filter *filter) {
    if (filter)
        atomic_fetch_add_explicit(&filter->ref_count, 1u, memory_order_relaxed);
    return filter;
}

void flux_blur_filter_release(flux_blur_filter *filter) {
    if (!filter)
        return;
    if (atomic_fetch_sub_explicit(&filter->ref_count, 1u, memory_order_acq_rel) != 1u)
        return;
    flux_device *device = filter->device;
    for (uint32_t i = 0; i < FLUX_MAX_FRAMES_IN_FLIGHT; ++i) {
        if (filter->slots[i].output)
            flux_image_release(filter->slots[i].output);
        if (filter->slots[i].quarter)
            flux_image_release(filter->slots[i].quarter);
        if (filter->slots[i].half)
            flux_image_release(filter->slots[i].half);
    }
    flux_internal_free(device, filter);
    flux_device_release(device);
}

static flux_result blur_filter_ensure_slot(flux_blur_filter *filter, uint32_t index,
                                           const flux_image *input, flux_format storage_format) {
    blur_filter_slot *slot = &filter->slots[index];
    if (slot->half && slot->quarter && slot->output && slot->width == input->width &&
        slot->height == input->height && slot->format == storage_format)
        return FLUX_OK;

    if (slot->output)
        flux_image_release(slot->output);
    if (slot->quarter)
        flux_image_release(slot->quarter);
    if (slot->half)
        flux_image_release(slot->half);
    *slot = (blur_filter_slot){0};

    uint32_t half_width = (input->width + 1u) / 2u;
    uint32_t half_height = (input->height + 1u) / 2u;
    uint32_t quarter_width = (half_width + 1u) / 2u;
    uint32_t quarter_height = (half_height + 1u) / 2u;
    flux_result r = flux_image_create_compute_writable(filter->device, half_width, half_height,
                                                       storage_format, &slot->half);
    if (r != FLUX_OK)
        return r;
    r = flux_image_create_compute_writable(filter->device, quarter_width, quarter_height,
                                           storage_format, &slot->quarter);
    if (r != FLUX_OK)
        goto fail;
    r = flux_image_create_compute_writable(filter->device, input->width, input->height,
                                           storage_format, &slot->output);
    if (r != FLUX_OK)
        goto fail;
    slot->width = input->width;
    slot->height = input->height;
    slot->format = storage_format;
    return FLUX_OK;

fail:
    if (slot->quarter)
        flux_image_release(slot->quarter);
    if (slot->half)
        flux_image_release(slot->half);
    *slot = (blur_filter_slot){0};
    return r;
}

static bool map_effect_region(const flux_effect_region *region, uint32_t root_width,
                              uint32_t root_height, uint32_t output_width, uint32_t output_height,
                              uint32_t *out_x, uint32_t *out_y, uint32_t *out_width,
                              uint32_t *out_height) {
    uint64_t x0 = region->x < root_width ? region->x : root_width;
    uint64_t y0 = region->y < root_height ? region->y : root_height;
    uint64_t x1 = (uint64_t)region->x + region->width;
    uint64_t y1 = (uint64_t)region->y + region->height;
    if (x1 > root_width)
        x1 = root_width;
    if (y1 > root_height)
        y1 = root_height;
    if (x1 <= x0 || y1 <= y0)
        return false;

    /* Map outward so a fractional pyramid edge can never discard a source
     * pixel requested by the caller. */
    uint64_t ox0 = x0 * output_width / root_width;
    uint64_t oy0 = y0 * output_height / root_height;
    uint64_t ox1 = (x1 * output_width + root_width - 1u) / root_width;
    uint64_t oy1 = (y1 * output_height + root_height - 1u) / root_height;
    if (ox1 > output_width)
        ox1 = output_width;
    if (oy1 > output_height)
        oy1 = output_height;
    if (ox1 <= ox0 || oy1 <= oy0)
        return false;
    *out_x = (uint32_t)ox0;
    *out_y = (uint32_t)oy0;
    *out_width = (uint32_t)(ox1 - ox0);
    *out_height = (uint32_t)(oy1 - oy0);
    return true;
}

static void record_backdrop_pass(effect_state *st, flux_device *device, VkCommandBuffer cmd,
                                 flux_image *input, flux_image *output, float offset, uint32_t mode,
                                 uint32_t root_width, uint32_t root_height,
                                 const flux_effect_region *regions, uint32_t region_count,
                                 bool is16f) {
    barrier_reuse_to_compute_write(cmd, output->image);
    flux_compute_pipeline *pipeline = st->backdrop_pipelines[is16f ? 1 : 0];
    effect_backdrop_push pc = {
        .in_handle = input->bindless,
        .sampler_handle = flux_device_default_sampler_handle(device),
        .out_handle = output->bindless_storage,
        .input_width = input->width,
        .input_height = input->height,
        .output_width = output->width,
        .output_height = output->height,
        .offset = offset,
        .mode = mode,
    };
    if (!regions || region_count == 0) {
        pc.region_width = output->width;
        pc.region_height = output->height;
        uint32_t gx = (output->width + EFFECT_BLUR_WG - 1u) / EFFECT_BLUR_WG;
        uint32_t gy = (output->height + EFFECT_BLUR_WG - 1u) / EFFECT_BLUR_WG;
        flux_compute_dispatch(cmd, pipeline, &pc, sizeof(pc), gx, gy, 1u);
    } else {
        bool dispatched = false;
        for (uint32_t i = 0; i < region_count; ++i) {
            if (!map_effect_region(&regions[i], root_width, root_height, output->width,
                                   output->height, &pc.origin_x, &pc.origin_y, &pc.region_width,
                                   &pc.region_height))
                continue;
            if (dispatched)
                barrier_compute_write_to_write(cmd, output->image);
            uint32_t gx = (pc.region_width + EFFECT_BLUR_WG - 1u) / EFFECT_BLUR_WG;
            uint32_t gy = (pc.region_height + EFFECT_BLUR_WG - 1u) / EFFECT_BLUR_WG;
            flux_compute_dispatch(cmd, pipeline, &pc, sizeof(pc), gx, gy, 1u);
            dispatched = true;
        }
    }
    barrier_compute_write_to_read(cmd, output->image);
}

static void record_backdrop_filter(effect_state *st, flux_device *device, VkCommandBuffer cmd,
                                   flux_image *input, blur_filter_slot *slot, float requested_sigma,
                                   const flux_effect_region *regions, uint32_t region_count,
                                   bool is16f) {
    float sigma = requested_sigma;
    if (!(sigma == sigma) || sigma < 0.0f)
        sigma = 0.0f;
    if (sigma > FLUX_EFFECT_BLUR_SIGMA_MAX)
        sigma = FLUX_EFFECT_BLUR_SIGMA_MAX;

    if (sigma == 0.0f) {
        record_backdrop_pass(st, device, cmd, input, slot->output, 0.0f, 2u, input->width,
                             input->height, regions, region_count, is16f);
        return;
    }

    /* Two pyramid levels provide a wide UI blur with fixed work. Sigma tunes
     * the sub-texel offsets rather than growing a per-pixel kernel loop. */
    float offset = fminf(fmaxf(sigma * 0.25f, 0.5f), 2.5f);
    record_backdrop_pass(st, device, cmd, input, slot->half, offset, 0u, input->width,
                         input->height, regions, region_count, is16f);
    record_backdrop_pass(st, device, cmd, slot->half, slot->quarter, offset, 0u, input->width,
                         input->height, regions, region_count, is16f);
    record_backdrop_pass(st, device, cmd, slot->quarter, slot->half, offset, 1u, input->width,
                         input->height, regions, region_count, is16f);
    record_backdrop_pass(st, device, cmd, slot->half, slot->output, offset, 1u, input->width,
                         input->height, regions, region_count, is16f);
}

flux_result flux_blur_filter_apply(flux_blur_filter *filter, flux_frame *frame,
                                   const flux_effect_blur_desc *desc, flux_image **out) {
    if (!filter || !frame || !desc || !out)
        return FLUX_ERROR_INVALID_ARGUMENT;
    *out = nullptr;
    if (desc->type != FLUX_TYPE_EFFECT_BLUR_DESC || !desc->input) {
        FLUX_FAIL(FLUX_ERROR_INVALID_ARGUMENT, "invalid reusable blur descriptor");
        return FLUX_ERROR_INVALID_ARGUMENT;
    }
    const flux_effect_blur_regions_desc *region_desc = desc->next;
    if (region_desc &&
        (region_desc->type != FLUX_TYPE_EFFECT_BLUR_REGIONS_DESC || region_desc->next ||
         (region_desc->region_count > 0 && !region_desc->regions))) {
        FLUX_FAIL(FLUX_ERROR_INVALID_ARGUMENT, "invalid reusable blur regions extension");
        return FLUX_ERROR_INVALID_ARGUMENT;
    }
    if (!frame->surface || frame->state != FLUX_FRAME_STATE_RECORDING || frame->pass_active) {
        FLUX_FAIL(FLUX_ERROR_INVALID_STATE,
                  "reusable blur requires a recording frame pass boundary");
        return FLUX_ERROR_INVALID_STATE;
    }
    flux_image *input = desc->input;
    if (frame->surface->device != filter->device || input->device != filter->device) {
        FLUX_FAIL(FLUX_ERROR_INVALID_ARGUMENT,
                  "blur filter, frame, and input use different devices");
        return FLUX_ERROR_INVALID_ARGUMENT;
    }
    if (input->bindless == FLUX_BINDLESS_INVALID) {
        FLUX_FAIL(FLUX_ERROR_INVALID_ARGUMENT, "reusable blur input lacks a sampled handle");
        return FLUX_ERROR_INVALID_ARGUMENT;
    }
    effect_state *st = effect_state_get_or_init(filter->device);
    if (!st)
        return FLUX_ERROR_OUT_OF_MEMORY;
    /* 8-bit SDR content takes the historic RGBA8 path; 16F working-space
     * content stays 16F so the pyramid runs in linear light (ADR-0069). */
    flux_format storage_format;
    bool is16f;
    flux_result rr = effect_resolve_storage(st, input, &storage_format, &is16f);
    if (rr != FLUX_OK)
        return rr;
    const flux_effect_region *regions = region_desc ? region_desc->regions : nullptr;
    uint32_t region_count = region_desc ? region_desc->region_count : 0u;
    if (region_count > 0) {
        bool any_valid = false;
        for (uint32_t i = 0; i < region_count; ++i) {
            uint32_t x, y, width, height;
            if (map_effect_region(&regions[i], input->width, input->height, input->width,
                                  input->height, &x, &y, &width, &height)) {
                any_valid = true;
                break;
            }
        }
        if (!any_valid) {
            FLUX_FAIL(FLUX_ERROR_INVALID_ARGUMENT,
                      "reusable blur region list has no pixels inside the input");
            return FLUX_ERROR_INVALID_ARGUMENT;
        }
    }
    uint32_t index = flux_frame_index(frame);
    if (index >= FLUX_MAX_FRAMES_IN_FLIGHT)
        return FLUX_ERROR_OUT_OF_RANGE;

    flux_result r = blur_filter_ensure_slot(filter, index, input, storage_format);
    if (r != FLUX_OK)
        return r;

    flux_platform_mutex_lock(&st->lock);
    r = ensure_backdrop_pipeline(filter->device, st, is16f);
    flux_platform_mutex_unlock(&st->lock);
    if (r != FLUX_OK)
        return r;

    blur_filter_slot *slot = &filter->slots[index];
    record_backdrop_filter(st, filter->device, flux_frame_vk_command_buffer(frame), input, slot,
                           desc->sigma, regions, region_count, is16f);
    *out = slot->output;
    return FLUX_OK;
}

