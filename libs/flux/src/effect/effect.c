static flux_result ensure_pipeline(flux_device *d, flux_compute_pipeline **slot,
                                   const unsigned char *spv, size_t spv_bytes,
                                   uint32_t push_bytes) {
    if (*slot)
        return FLUX_OK;
    flux_compute_pipeline_desc pdesc = FLUX_COMPUTE_PIPELINE_DESC_INIT;
    pdesc.spirv = (const uint32_t *)spv;
    pdesc.spirv_word_count = spv_bytes / sizeof(uint32_t);
    pdesc.entry_point = "main";
    pdesc.push_constant_bytes = push_bytes;
    flux_result r = flux_compute_pipeline_create(d, &pdesc, slot);
    if (r != FLUX_OK)
        return r;
    /* The pipeline lives in per-device module state and is released
     * by effect_state_destroy inside flux_device_release; a strong
     * device ref would cycle and leak the whole device. */
    flux_compute_pipeline_make_device_weak(*slot);
    return FLUX_OK;
}

static flux_result ensure_blur_pipeline(flux_device *d, effect_state *st, bool is16f) {
    return ensure_pipeline(d, &st->blur_pipelines[is16f ? 1 : 0],
                           is16f ? effect_blur_16f_spv : effect_blur_spv,
                           is16f ? sizeof(effect_blur_16f_spv) : sizeof(effect_blur_spv),
                           sizeof(effect_blur_push));
}

static flux_result ensure_backdrop_pipeline(flux_device *d, effect_state *st, bool is16f) {
    return ensure_pipeline(d, &st->backdrop_pipelines[is16f ? 1 : 0],
                           is16f ? effect_backdrop_16f_spv : effect_backdrop_spv,
                           is16f ? sizeof(effect_backdrop_16f_spv) : sizeof(effect_backdrop_spv),
                           sizeof(effect_backdrop_push));
}

/* Storage/intermediate format for an effect input (ADR-0069): 8-bit
 * SDR content keeps the historic RGBA8 path; 16F working-space content
 * stays 16F so blurring runs in linear light — when the device
 * advertises rgba16f storage. */
static flux_result effect_resolve_storage(effect_state *st, const flux_image *in,
                                          flux_format *out, bool *out_16f) {
    if (in->format == FLUX_FORMAT_RGBA8_UNORM || in->format == FLUX_FORMAT_BGRA8_UNORM) {
        *out = FLUX_FORMAT_RGBA8_UNORM;
        *out_16f = false;
        return FLUX_OK;
    }
    if (in->format == FLUX_FORMAT_RGBA16_SFLOAT) {
        if (!st->storage_16f_supported) {
            FLUX_FAIL(FLUX_ERROR_UNSUPPORTED,
                      "16F effect input needs rgba16f storage support on this device");
            return FLUX_ERROR_UNSUPPORTED;
        }
        *out = FLUX_FORMAT_RGBA16_SFLOAT;
        *out_16f = true;
        return FLUX_OK;
    }
    FLUX_FAIL(FLUX_ERROR_UNSUPPORTED,
              "effect input format not supported (use RGBA8/BGRA8_UNORM or RGBA16_SFLOAT)");
    return FLUX_ERROR_UNSUPPORTED;
}

