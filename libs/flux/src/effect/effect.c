#define EFFECT_BLUR_RADIUS_MAX 64

/* ------------------------------------------------------------------ */
/*  Module state                                                      */
/* ------------------------------------------------------------------ */

/* Cached intermediate target keyed by (format, width, height). One
 * intermediate per key is enough — the horizontal pass writes it,
 * the vertical pass reads it, and the two passes are serialised
 * within a single flux_effect_blur call. Callers issuing concurrent
 * blurs on the same device are already required to serialise per
 * the header doc. */
typedef struct intermediate_entry {
    uint32_t width;
    uint32_t height;
    flux_format format;
    flux_image *image;
    bool leased;
    struct intermediate_entry *next;
} intermediate_entry;

/* Intermediate and output slots are exclusively leased within one reset epoch.
 * They are returned to the pool only at a caller-proven GPU quiescent point. */
typedef struct output_entry {
    uint32_t width;
    uint32_t height;
    flux_format format;
    flux_image *image;
    bool leased;
    struct output_entry *next;
} output_entry;

typedef struct effect_state {
    flux_platform_mutex lock;
    /* Pipeline slots, indexed by storage class: [0] rgba8, [1] rgba16f
     * (ADR-0069: 16F for working-space content when the device
     * advertises rgba16f storage). Lazily built; shared across calls. */
    flux_compute_pipeline *blur_pipelines[2];
    flux_compute_pipeline *backdrop_pipelines[2]; /* fixed-cost live-compositor filter */
    bool storage_16f_supported; /* VK_FORMAT_R16G16B16A16_SFLOAT STORAGE_IMAGE */
    intermediate_entry *intermediates;
    output_entry *outputs;
} effect_state;

typedef struct blur_filter_slot {
    uint32_t width;
    uint32_t height;
    flux_format format;
    flux_image *half;
    flux_image *quarter;
    flux_image *output;
} blur_filter_slot;

struct flux_blur_filter {
    atomic_uint ref_count;
    flux_device *device; /* retained; slot images hold weak device refs */
    blur_filter_slot slots[FLUX_MAX_FRAMES_IN_FLIGHT];
};

static void effect_state_destroy(flux_device *d) {
    effect_state *st = d->effect_state;
    if (!st)
        return;

    for (output_entry *o = st->outputs; o;) {
        output_entry *next = o->next;
        if (o->image)
            flux_image_release(o->image);
        flux_internal_free(d, o);
        o = next;
    }
    for (intermediate_entry *e = st->intermediates; e;) {
        intermediate_entry *next = e->next;
        if (e->image)
            flux_image_release(e->image);
        flux_internal_free(d, e);
        e = next;
    }
    if (st->blur_pipelines[0])
        flux_compute_pipeline_release(st->blur_pipelines[0]);
    if (st->blur_pipelines[1])
        flux_compute_pipeline_release(st->blur_pipelines[1]);
    if (st->backdrop_pipelines[0])
        flux_compute_pipeline_release(st->backdrop_pipelines[0]);
    if (st->backdrop_pipelines[1])
        flux_compute_pipeline_release(st->backdrop_pipelines[1]);
    flux_platform_mutex_destroy(&st->lock);
    flux_internal_free(d, st);
    d->effect_state = nullptr;
    d->effect_state_destroy = nullptr;
}

static effect_state *effect_state_get_or_init(flux_device *d) {
    flux_platform_mutex_lock(&d->module_state_lock);
    effect_state *published = d->effect_state;
    flux_platform_mutex_unlock(&d->module_state_lock);
    if (published)
        return published;

    effect_state *candidate = flux_internal_alloc(d, sizeof(*candidate));
    if (!candidate)
        return nullptr;
    if (!flux_platform_mutex_init(&candidate->lock)) {
        flux_internal_free(d, candidate);
        return nullptr;
    }
    /* rgba16f storage is an optional format feature; resolve once per
     * device (ADR-0069's "effects accept 16F when the device advertises
     * the format features"). */
    {
        VkFormatProperties props;
        vkGetPhysicalDeviceFormatProperties(d->physical_device,
                                            VK_FORMAT_R16G16B16A16_SFLOAT, &props);
        candidate->storage_16f_supported =
            (props.optimalTilingFeatures & VK_FORMAT_FEATURE_STORAGE_IMAGE_BIT) != 0;
    }

    flux_platform_mutex_lock(&d->module_state_lock);
    if (!d->effect_state) {
        d->effect_state = candidate;
        d->effect_state_destroy = effect_state_destroy;
        published = candidate;
        candidate = nullptr;
    } else {
        published = d->effect_state;
    }
    flux_platform_mutex_unlock(&d->module_state_lock);

    if (candidate) {
        flux_platform_mutex_destroy(&candidate->lock);
        flux_internal_free(d, candidate);
    }
    return published;
}

