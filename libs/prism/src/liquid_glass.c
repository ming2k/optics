flux_result prism_liquid_glass_filter_create(flux_device *device,
                                             prism_liquid_glass_filter **out) {
    if (!device || !out)
        return FLUX_ERROR_INVALID_ARGUMENT;
    *out = nullptr;
    prism_liquid_glass_filter *filter = calloc(1, sizeof(*filter));
    if (!filter)
        return FLUX_ERROR_OUT_OF_MEMORY;
    atomic_init(&filter->ref_count, 1u);
    filter->device = flux_device_retain(device);
    *out = filter;
    return FLUX_OK;
}

prism_liquid_glass_filter *prism_liquid_glass_filter_retain(prism_liquid_glass_filter *filter) {
    if (filter)
        atomic_fetch_add_explicit(&filter->ref_count, 1u, memory_order_relaxed);
    return filter;
}

void prism_liquid_glass_filter_release(prism_liquid_glass_filter *filter) {
    if (!filter)
        return;
    if (atomic_fetch_sub_explicit(&filter->ref_count, 1u, memory_order_acq_rel) != 1u)
        return;
    flux_device *device = filter->device;
    for (uint32_t i = 0; i < FLUX_MAX_FRAMES_IN_FLIGHT; ++i) {
        if (filter->slots[i].output)
            flux_image_release(filter->slots[i].output);
        if (filter->slots[i].stats)
            flux_buffer_release(filter->slots[i].stats);
    }
    /* Pipelines are destroyed inline by flux; the header's release
     * contract (all referencing GPU work completed) covers this. */
    if (filter->glass_pipeline)
        flux_compute_pipeline_release(filter->glass_pipeline);
    if (filter->clear_pipeline)
        flux_compute_pipeline_release(filter->clear_pipeline);
    if (filter->stats_pipeline)
        flux_compute_pipeline_release(filter->stats_pipeline);
    free(filter);
    flux_device_release(device);
}

static flux_result liquid_glass_ensure_stats_buffer(prism_liquid_glass_filter *filter,
                                                    liquid_glass_filter_slot *slot) {
    if (slot->stats)
        return FLUX_OK;
    flux_buffer_desc bdesc = FLUX_BUFFER_DESC_INIT;
    bdesc.size = PRISM_STATS_BYTES;
    bdesc.usage = FLUX_BUFFER_USAGE_STORAGE;
    /* HOST_VISIBLE is HOST_COHERENT in flux: the shader's writes are
     * visible to the CPU after the slot's fence, no flush/invalidate. */
    bdesc.location = FLUX_BUFFER_HOST_VISIBLE;
    bdesc.device_address = true; /* stats shader writes via buffer reference */
    return flux_buffer_create(filter->device, &bdesc, &slot->stats);
}

static flux_result liquid_glass_ensure_slot(prism_liquid_glass_filter *filter, uint32_t index,
                                            const flux_image *input, bool need_stats) {
    liquid_glass_filter_slot *slot = &filter->slots[index];
    uint32_t width = flux_image_width(input);
    uint32_t height = flux_image_height(input);
    if (slot->output && slot->width == width && slot->height == height)
        return need_stats ? liquid_glass_ensure_stats_buffer(filter, slot) : FLUX_OK;
    if (slot->output)
        flux_image_release(slot->output);
    if (slot->stats)
        flux_buffer_release(slot->stats);
    *slot = (liquid_glass_filter_slot){0};
    flux_result r = flux_image_create_compute_writable(filter->device, width, height,
                                                       PRISM_STORAGE_FORMAT, &slot->output);
    if (r != FLUX_OK)
        return r;
    slot->width = width;
    slot->height = height;
    if (need_stats) {
        r = liquid_glass_ensure_stats_buffer(filter, slot);
        if (r != FLUX_OK)
            return r;
    }
    return FLUX_OK;
}

/* The material pipelines are per-filter and lazily built: prism has no
 * per-device module state of its own, and the filter contract already
 * requires callers to serialize per device. */
static flux_result liquid_glass_ensure_pipelines(prism_liquid_glass_filter *filter, bool need_clear,
                                                 bool need_glass, bool need_stats) {
    if (need_clear && !filter->clear_pipeline) {
        flux_compute_pipeline_desc pdesc = FLUX_COMPUTE_PIPELINE_DESC_INIT;
        pdesc.spirv = (const uint32_t *)storage_clear_spv;
        pdesc.spirv_word_count = sizeof(storage_clear_spv) / sizeof(uint32_t);
        pdesc.entry_point = "main";
        pdesc.push_constant_bytes = sizeof(storage_clear_push);
        flux_result r = flux_compute_pipeline_create(filter->device, &pdesc, &filter->clear_pipeline);
        if (r != FLUX_OK)
            return r;
    }
    if (need_glass && !filter->glass_pipeline) {
        flux_compute_pipeline_desc pdesc = FLUX_COMPUTE_PIPELINE_DESC_INIT;
        pdesc.spirv = (const uint32_t *)liquid_glass_spv;
        pdesc.spirv_word_count = sizeof(liquid_glass_spv) / sizeof(uint32_t);
        pdesc.entry_point = "main";
        pdesc.push_constant_bytes = sizeof(liquid_glass_push);
        flux_result r = flux_compute_pipeline_create(filter->device, &pdesc, &filter->glass_pipeline);
        if (r != FLUX_OK)
            return r;
    }
    if (need_stats && !filter->stats_pipeline) {
        flux_compute_pipeline_desc pdesc = FLUX_COMPUTE_PIPELINE_DESC_INIT;
        pdesc.spirv = (const uint32_t *)backdrop_stats_spv;
        pdesc.spirv_word_count = sizeof(backdrop_stats_spv) / sizeof(uint32_t);
        pdesc.entry_point = "main";
        pdesc.push_constant_bytes = sizeof(backdrop_stats_push);
        flux_result r = flux_compute_pipeline_create(filter->device, &pdesc, &filter->stats_pipeline);
        if (r != FLUX_OK)
            return r;
    }
    return FLUX_OK;
}

