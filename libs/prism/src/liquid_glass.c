static bool valid_liquid_glass_desc(const prism_liquid_glass_desc *desc) {
    if (desc->type != PRISM_TYPE_LIQUID_GLASS_DESC || !desc->input || !desc->blurred_input ||
        desc->group_count > LIQUID_GLASS_MAX_GROUPS || (desc->group_count > 0u && !desc->groups))
        return false;
    if (!isfinite(desc->refraction) || !isfinite(desc->chromatic_aberration) ||
        !isfinite(desc->saturation) || !isfinite(desc->brightness) || !isfinite(desc->edge_width) ||
        !isfinite(desc->rim_light) || !isfinite(desc->light_direction.x) ||
        !isfinite(desc->light_direction.y) || !isfinite(desc->opacity) ||
        !isfinite(desc->size_reference) || !isfinite(desc->size_scale_min) ||
        !isfinite(desc->tint_strength) || !isfinite(desc->frost_strength))
        return false;
    for (uint32_t i = 0; i < desc->group_count; ++i) {
        if (!liquid_glass_group_is_valid(&desc->groups[i]))
            return false;
    }
    return true;
}

static void copy_shape(float out[4], prism_liquid_glass_shape shape) {
    out[0] = shape.bounds.x;
    out[1] = shape.bounds.y;
    out[2] = shape.bounds.w;
    out[3] = shape.bounds.h;
}

static void record_storage_clear_regions(prism_liquid_glass_filter *filter, VkCommandBuffer command,
                                         flux_image *output, const liquid_glass_region *regions,
                                         uint32_t region_count) {
    for (uint32_t i = 0; i < region_count; ++i) {
        liquid_glass_region region = regions[i];
        storage_clear_push push = {
            .output_handle = flux_image_bindless_storage_handle(output),
            .width = flux_image_width(output),
            .height = flux_image_height(output),
            .origin_x = region.x,
            .origin_y = region.y,
            .region_width = region.width,
            .region_height = region.height,
        };
        uint32_t gx = (region.width + PRISM_WG - 1u) / PRISM_WG;
        uint32_t gy = (region.height + PRISM_WG - 1u) / PRISM_WG;
        flux_compute_dispatch(command, filter->clear_pipeline, &push, sizeof(push), gx, gy, 1u);
    }
}

flux_result prism_liquid_glass_filter_apply(prism_liquid_glass_filter *filter, flux_frame *frame,
                                            const prism_liquid_glass_desc *desc, flux_image **out) {
    if (!filter || !frame || !desc || !out)
        return FLUX_ERROR_INVALID_ARGUMENT;
    *out = nullptr;
    if (!valid_liquid_glass_desc(desc))
        return FLUX_ERROR_INVALID_ARGUMENT;
    if (flux_frame_get_state(frame) != FLUX_FRAME_STATE_RECORDING ||
        flux_frame_has_active_pass(frame))
        return FLUX_ERROR_INVALID_STATE;
    flux_image *input = desc->input;
    flux_image *blurred = desc->blurred_input;
    if (flux_frame_device(frame) != filter->device || flux_image_device(input) != filter->device ||
        flux_image_device(blurred) != filter->device)
        return FLUX_ERROR_INVALID_ARGUMENT;
    if (flux_image_width(input) != flux_image_width(blurred) ||
        flux_image_height(input) != flux_image_height(blurred) ||
        (flux_image_format(input) != FLUX_FORMAT_RGBA8_UNORM &&
         flux_image_format(input) != FLUX_FORMAT_BGRA8_UNORM) ||
        flux_image_format(blurred) != FLUX_FORMAT_RGBA8_UNORM ||
        flux_image_bindless_handle(input) == FLUX_BINDLESS_INVALID ||
        flux_image_bindless_handle(blurred) == FLUX_BINDLESS_INVALID)
        return FLUX_ERROR_UNSUPPORTED;
    uint32_t index = flux_frame_index(frame);
    if (index >= FLUX_MAX_FRAMES_IN_FLIGHT)
        return FLUX_ERROR_OUT_OF_RANGE;
    flux_result result = liquid_glass_ensure_slot(filter, index, input, desc->group_count > 0u);
    if (result != FLUX_OK)
        return result;

    uint32_t image_width = flux_image_width(input);
    uint32_t image_height = flux_image_height(input);
    liquid_glass_filter_slot *slot = &filter->slots[index];
    liquid_glass_region current[LIQUID_GLASS_MAX_GROUPS];
    uint32_t current_group_indices[LIQUID_GLASS_MAX_GROUPS];
    uint32_t current_count = 0u;
    for (uint32_t i = 0; i < desc->group_count; ++i) {
        const prism_liquid_glass_group *group = &desc->groups[i];
        /* The body's shadow reaches its downward offset plus the falloff. */
        float shadow_reach = group->shadow_alpha > 0.0f ? fmaxf(group->shadow_offset_y, 0.0f) +
                                                              2.0f * fmaxf(group->shadow_blur, 0.0f)
                                                        : 0.0f;
        liquid_glass_region region;
        if (!liquid_glass_group_dispatch_bounds(group, shadow_reach, image_width, image_height,
                                                &region))
            continue;
        current[current_count] = region;
        current_group_indices[current_count] = i;
        ++current_count;
    }

    liquid_glass_region clear_regions[LIQUID_GLASS_MAX_CLEAR_REGIONS];
    uint32_t clear_count = 0u;
    if (!liquid_glass_build_clear_regions(
            slot->initialized, image_width, image_height, slot->previous, slot->previous_count,
            current, current_count, clear_regions, LIQUID_GLASS_MAX_CLEAR_REGIONS, &clear_count))
        return FLUX_ERROR_INVALID_STATE;

    result = liquid_glass_ensure_pipelines(filter, clear_count > 0u, current_count > 0u,
                                           desc->group_count > 0u);
    if (result != FLUX_OK)
        return result;

    VkCommandBuffer command = flux_frame_vk_command_buffer(frame);
    VkImage output_image = flux_image_vk_image(slot->output);
    if (clear_count > 0u) {
        if (slot->initialized)
            barrier_reuse_to_compute_write(command, output_image);
        record_storage_clear_regions(filter, command, slot->output, clear_regions, clear_count);
        if (current_count > 0u)
            barrier_compute_write_to_read_write(command, output_image);
    }

    /* Backdrop statistics: one 16x16 workgroup per group reduces the
     * primary body's backdrop into (mean luminance, high-frequency energy)
     * for the frame-lagged CPU read. Off-screen bodies reduce an empty
     * rect, which the shader reports as zeros. Runs before the glass
     * dispatches; it shares only their sampled inputs. */
    if (desc->group_count > 0u) {
        uint64_t stats_address = flux_buffer_device_address(slot->stats);
        for (uint32_t i = 0; i < desc->group_count; ++i) {
            liquid_glass_region rect =
                liquid_glass_group_stats_bounds(&desc->groups[i], image_width, image_height);
            backdrop_stats_push spush = {
                .input_handle = flux_image_bindless_handle(input),
                .blurred_handle = flux_image_bindless_handle(blurred),
                .sampler_handle = flux_device_default_sampler_handle(filter->device),
                .width = image_width,
                .height = image_height,
                .rect_x = rect.x,
                .rect_y = rect.y,
                .rect_width = rect.width,
                .rect_height = rect.height,
                .group_index = i,
                .stats_address_lo = (uint32_t)(stats_address & 0xFFFFFFFFu),
                .stats_address_hi = (uint32_t)(stats_address >> 32u),
            };
            flux_compute_dispatch(command, filter->stats_pipeline, &spush, sizeof(spush), 1u, 1u,
                                  1u);
        }
        barrier_stats_write_to_compute(command, flux_buffer_vk_buffer(slot->stats));
    }

    bool dispatched = false;
    for (uint32_t i = 0; i < current_count; ++i) {
        const prism_liquid_glass_group *group = &desc->groups[current_group_indices[i]];
        liquid_glass_region region = current[i];
        if (dispatched)
            barrier_compute_write_to_read_write(command, output_image);
        /* Per-group overrides: a negative value inherits the desc knob. */
        float saturation = liquid_glass_group_or_desc(group->saturation, desc->saturation);
        float tint_strength = liquid_glass_group_or_desc(group->tint_strength, desc->tint_strength);
        float frost_strength =
            liquid_glass_group_or_desc(group->frost_strength, desc->frost_strength);
        float size_reference = fmaxf(desc->size_reference, 0.0f);
        float size_scale_min = fminf(fmaxf(desc->size_scale_min, 0.0f), 1.0f);
        liquid_glass_push push = {
            .input_handle = flux_image_bindless_handle(input),
            .blurred_handle = flux_image_bindless_handle(blurred),
            .sampler_handle = flux_device_default_sampler_handle(filter->device),
            .output_handle = flux_image_bindless_storage_handle(slot->output),
            .width = image_width,
            .height = image_height,
            .origin_x = region.x,
            .origin_y = region.y,
            .radius0 = fmaxf(group->shapes[0].corner_radius, 0.0f),
            .radius1 = group->focus_strength > 0.0f
                           ? fmaxf(group->focus.corner_radius, 0.0f)
                           : (group->shape_count == 2u ? fmaxf(group->shapes[1].corner_radius, 0.0f)
                                                       : 0.0f),
            .blend_radius = fmaxf(group->blend_radius, 0.0f),
            .opacity = fminf(fmaxf(group->opacity * desc->opacity, 0.0f), 1.0f),
            .refraction = fmaxf(desc->refraction, 0.0f),
            .chromatic_aberration = fmaxf(desc->chromatic_aberration, 0.0f),
            .saturation = fmaxf(saturation, 0.0f),
            .brightness = fmaxf(desc->brightness, 0.0f),
            .edge_width = fmaxf(desc->edge_width, 1.0f),
            .rim_light = fmaxf(desc->rim_light, 0.0f),
            .light_x = desc->light_direction.x,
            .light_y = desc->light_direction.y,
            .group_width = region.width,
            .group_height = region.height,
            .tint_color_shape_count = (group->tint_color & 0x00FFFFFFu) | (group->shape_count << 24u),
            .shadow_alpha = fminf(fmaxf(group->shadow_alpha, 0.0f), 1.0f),
            .shadow_blur = fmaxf(group->shadow_blur, 0.0f),
            .shadow_offset_y = group->shadow_offset_y,
            .size_params = (uint32_t)liquid_glass_f32_to_f16(size_reference) |
                           ((uint32_t)liquid_glass_f32_to_f16(size_scale_min) << 16u),
            .tint_strength = fmaxf(tint_strength, 0.0f),
            .frost_strength = fmaxf(frost_strength, 0.0f),
            .focus_strength = fminf(fmaxf(group->focus_strength, 0.0f), 1.0f),
            .plate_polarity = group->plate_polarity,
            .backdrop_energy = group->backdrop_energy,
        };
        copy_shape(push.shape0, group->shapes[0]);
        if (group->focus_strength > 0.0f)
            copy_shape(push.shape1, group->focus);
        else if (group->shape_count == 2u)
            copy_shape(push.shape1, group->shapes[1]);
        uint32_t gx = (region.width + PRISM_WG - 1u) / PRISM_WG;
        uint32_t gy = (region.height + PRISM_WG - 1u) / PRISM_WG;
        flux_compute_dispatch(command, filter->glass_pipeline, &push, sizeof(push), gx, gy, 1u);
        dispatched = true;
    }
    /* Both the transparent region clear and liquid material are compute
     * storage writes. Make the persistent output visible to its following
     * Canvas sample, including a clear-only apply after all groups disappear. */
    if (clear_count > 0u || dispatched)
        barrier_compute_write_to_read(command, output_image);

    if (current_count > 0u)
        memcpy(slot->previous, current, current_count * sizeof(current[0]));
    slot->previous_count = current_count;
    slot->initialized = true;
    slot->stats_submitted = true;
    /* A zero-group apply submits no stats; the frame-lagged read then
     * honestly reports zero groups for this slot's last submission. */
    slot->stats_group_count = desc->group_count;
    *out = slot->output;
    return FLUX_OK;
}

flux_result prism_liquid_glass_filter_stats(prism_liquid_glass_filter *filter, flux_frame *frame,
                                            prism_backdrop_stat *out, uint32_t max_groups,
                                            uint32_t *out_count) {
    if (!filter || !frame || !out_count || (max_groups > 0u && !out))
        return FLUX_ERROR_INVALID_ARGUMENT;
    *out_count = 0u;
    if (flux_frame_device(frame) != filter->device)
        return FLUX_ERROR_INVALID_ARGUMENT;
    /* The mapped buffer is stable only while this frame records: its
     * begin_frame waited the slot's fence. */
    if (flux_frame_get_state(frame) != FLUX_FRAME_STATE_RECORDING)
        return FLUX_ERROR_INVALID_STATE;
    uint32_t index = flux_frame_index(frame);
    if (index >= FLUX_MAX_FRAMES_IN_FLIGHT)
        return FLUX_ERROR_OUT_OF_RANGE;
    const liquid_glass_filter_slot *slot = &filter->slots[index];
    if (!slot->stats_submitted || !slot->stats)
        return FLUX_ERROR_INVALID_STATE;
    uint32_t count =
        slot->stats_group_count < max_groups ? slot->stats_group_count : max_groups;
    if (count > 0u)
        memcpy(out, flux_buffer_mapped(slot->stats), count * sizeof(*out));
    *out_count = count;
    return FLUX_OK;
}
