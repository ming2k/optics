static void lane_icc_profile(flux_device *d) {
    /* Device-free profile parsing: a valid profile allocates a host wrapper
     * that must be released. A rejected body allocates nothing. Both paths
     * must leave the host row exactly where it started. */
    LANE("host");
    flux_icc_profile *p = nullptr;
    (void)flux_icc_profile_create("not-a-profile", 13, &p);
    if (p)
        flux_icc_profile_release(p);
    LANE_END("host", "flux_icc_profile");
}

