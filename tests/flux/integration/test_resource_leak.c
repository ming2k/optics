static void lane_graphics_pipeline(flux_device *d) {
    flux_graphics_pipeline_desc pd = FLUX_GRAPHICS_PIPELINE_DESC_INIT;
    pd.vertex_spirv = (const uint32_t *)vert_spv;
    pd.vertex_spirv_word_count = sizeof(vert_spv) / sizeof(uint32_t);
    pd.fragment_spirv = (const uint32_t *)frag_spv;
    pd.fragment_spirv_word_count = sizeof(frag_spv) / sizeof(uint32_t);
    pd.topology = FLUX_TOPOLOGY_TRIANGLE_LIST;
    pd.cull = FLUX_CULL_NONE;
    pd.blend = FLUX_BLEND_PRESET_NONE;
    pd.depth = FLUX_DEPTH_NONE;
    pd.color_format = FLUX_FORMAT_BGRA8_UNORM;
    pd.depth_format = FLUX_FORMAT_UNDEFINED;

    flux_graphics_pipeline *warm = nullptr;
    if (flux_graphics_pipeline_create(d, &pd, &warm) != FLUX_OK) {
        fprintf(stderr, "note: graphics pipeline unavailable; lane skipped\n");
        return;
    }
    flux_graphics_pipeline_release(warm);
    flux_device_wait_idle(d);

    LANE("vk_pipeline");
    flux_graphics_pipeline *gp = nullptr;
    EXPECT(flux_graphics_pipeline_create(d, &pd, &gp) == FLUX_OK);
    expect_rose(d, SCOPE, "vk_pipeline", OWNER, &before_, "flux_graphics_pipeline_create");
    flux_graphics_pipeline_release(gp);
    LANE_END("vk_pipeline", "flux_graphics_pipeline");
}

/* ------------------------------------------------------------------ */
/*  Frame-scope enforcement (ADR-0129 decision 4)                     */
/* ------------------------------------------------------------------ */

/* The per-frame drain check is the only drain point that can be enforced
 * continuously without stalling, so it is the one that catches the largest
 * regression class — a per-frame acquire whose release is missing — within a
 * single frame instead of at process exit.
 *
 * A balanced frame-lifetime row must leave the check clean; an unbalanced one
 * must make it report. A check that only ever returned true would be
 * indistinguishable from no check at all, which is why both directions are
 * asserted here. */
static void lane_frame_scope_drain(flux_device *d) {
    const char *kind = "frame_probe";
    const char *owner = "tests/observe";

    /* Balanced: acquire then release, check is clean. */
    EXPECT(FLUX_OBSERVE_ACQUIRE(d, FLUX_SCOPE_CONTEXT, FLUX_LIFETIME_FRAME, kind, owner, 0,
                                FLUX_SITE_NONE));
    FLUX_OBSERVE_RELEASE(d, FLUX_SCOPE_CONTEXT, kind, owner, 0);
    EXPECT(flux_observe_frame_drain_check(d));

    /* Unbalanced: the check must report, and must report at the frame
     * boundary rather than waiting for teardown. */
    EXPECT(FLUX_OBSERVE_ACQUIRE(d, FLUX_SCOPE_CONTEXT, FLUX_LIFETIME_FRAME, kind, owner, 0,
                                FLUX_SITE_NONE));
    EXPECT(!flux_observe_frame_drain_check(d));

    FLUX_OBSERVE_RELEASE(d, FLUX_SCOPE_CONTEXT, kind, owner, 0);
    EXPECT(flux_observe_frame_drain_check(d));
}

/* ------------------------------------------------------------------ */
/*  Bindless double release (ADR-0131)                                */
/* ------------------------------------------------------------------ */

/* A duplicated release used to push the slot a second time, after which two
 * registrations popped the same index and one resource was silently
 * re-pointed at the other. The heap must now refuse it and stay stable. */
static void lane_bindless_double_release(flux_device *d) {
    uint32_t px[4] = {0};
    flux_image *imgs[3] = {nullptr, nullptr, nullptr};
    flux_bindless_handle handles[3] = {FLUX_BINDLESS_INVALID, FLUX_BINDLESS_INVALID,
                                       FLUX_BINDLESS_INVALID};

    for (int i = 0; i < 3; ++i) {
        flux_image_desc id = FLUX_IMAGE_DESC_INIT;
        id.width = 2;
        id.height = 2;
        id.format = FLUX_FORMAT_RGBA8_UNORM;
        id.initial_data = px;
        EXPECT(flux_image_create(d, &id, &imgs[i]) == FLUX_OK);
        handles[i] = flux_image_bindless_handle(imgs[i]);
        EXPECT(handles[i] != FLUX_BINDLESS_INVALID);
    }
    /* Three distinct slots: the heap must never hand out an alias. */
    EXPECT(handles[0] != handles[1]);
    EXPECT(handles[1] != handles[2]);
    EXPECT(handles[0] != handles[2]);

    /* Release the middle image, then duplicate its release through the public
     * bindless path. The second call must be refused, not corrupt the stack. */
    flux_image_release(imgs[1]);
    imgs[1] = nullptr;
    flux_bindless_release(d, handles[1]); /* duplicate: refused */
    flux_device_wait_idle(d);

    /* A fourth image must still land on a valid, previously-free slot and not
     * collide with the two live images' slots. */
    flux_image *fourth = nullptr;
    flux_image_desc id = FLUX_IMAGE_DESC_INIT;
    id.width = 2;
    id.height = 2;
    id.format = FLUX_FORMAT_RGBA8_UNORM;
    id.initial_data = px;
    EXPECT(flux_image_create(d, &id, &fourth) == FLUX_OK);
    flux_bindless_handle h4 = flux_image_bindless_handle(fourth);
    EXPECT(h4 != handles[0]);
    EXPECT(h4 != handles[2]);

    flux_image_release(fourth);
    flux_image_release(imgs[0]);
    flux_image_release(imgs[2]);
    flux_device_wait_idle(d);
}

/* ------------------------------------------------------------------ */
/*  Leak visibility: the ledger must actually see a deliberate leak   */
/* ------------------------------------------------------------------ */

/* A detector that cannot fire on a known leak is decoration. This lane
 * deliberately leaks one image and requires the report to name it. */
static void lane_detects_a_real_leak(flux_device *d) {
    uint32_t px[4] = {0};
    flux_image_desc id = FLUX_IMAGE_DESC_INIT;
    id.width = 2;
    id.height = 2;
    id.format = FLUX_FORMAT_RGBA8_UNORM;
    id.initial_data = px;

    flux_observe_entry rows[64] = {};
    flux_observe_counters before = row_of(d, SCOPE, "vk_memory", OWNER);

    flux_image *leaked = nullptr;
    EXPECT(flux_image_create(d, &id, &leaked) == FLUX_OK);

    flux_observe_response resp = flux_observe_report(d, &(flux_observe_report_opts){
                                                            .type = FLUX_TYPE_OBSERVE_REPORT_OPTS,
                                                            .entries = rows,
                                                            .capacity = 64,
                                                            .scope = SCOPE,
                                                        });
    EXPECT(resp.result == FLUX_OK);
    EXPECT(resp.overflowed_kinds == 0);

    bool saw_vk_memory = false;
    for (uint32_t i = 0; i < resp.count; ++i) {
        if (strcmp(rows[i].kind, "vk_memory") == 0) {
            saw_vk_memory = true;
            EXPECT(rows[i].live >= 1);
            EXPECT(rows[i].bytes_live > 0);
            /* A leaking row must carry its creation site: that is the whole
             * difference between this and the old byte-total warning. */
            EXPECT(rows[i].site != nullptr);
        }
    }
    EXPECT(saw_vk_memory);

    flux_image_release(leaked);
    flux_device_wait_idle(d);
    expect_drained(d, SCOPE, "vk_memory", OWNER, &before, "deliberate-leak probe (post-release)");
}

int main(void) {
    flux_device *d = test_helpers_make_headless_device();
    if (!d) {
        fprintf(stderr, "test_resource_leak: no Vulkan device; skipping\n");
        TEST_SUMMARY();
    }

    lane_image(d);
    lane_sampler(d);
    lane_buffer(d);
    lane_target(d);
    lane_icc_profile(d);
    lane_graphics_pipeline(d);
    lane_frame_scope_drain(d);
    lane_bindless_double_release(d);
    lane_detects_a_real_leak(d);

    flux_device_release(d);
    TEST_SUMMARY();
}
