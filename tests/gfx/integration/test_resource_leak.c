static void lane_graphics_pipeline(optics_gfx_device *d) {
    optics_gfx_graphics_pipeline_desc pd = OPTICS_GFX_GRAPHICS_PIPELINE_DESC_INIT;
    pd.vertex_spirv = (const uint32_t *)vert_spv;
    pd.vertex_spirv_word_count = sizeof(vert_spv) / sizeof(uint32_t);
    pd.fragment_spirv = (const uint32_t *)frag_spv;
    pd.fragment_spirv_word_count = sizeof(frag_spv) / sizeof(uint32_t);
    pd.topology = OPTICS_GFX_TOPOLOGY_TRIANGLE_LIST;
    pd.cull = OPTICS_GFX_CULL_NONE;
    pd.blend = OPTICS_GFX_BLEND_PRESET_NONE;
    pd.depth = OPTICS_GFX_DEPTH_NONE;
    pd.color_format = OPTICS_GFX_FORMAT_BGRA8_UNORM;
    pd.depth_format = OPTICS_GFX_FORMAT_UNDEFINED;

    optics_gfx_graphics_pipeline *warm = nullptr;
    if (optics_gfx_graphics_pipeline_create(d, &pd, &warm) != OPTICS_GFX_OK) {
        fprintf(stderr, "note: graphics pipeline unavailable; lane skipped\n");
        return;
    }
    optics_gfx_graphics_pipeline_release(warm);
    optics_gfx_device_wait_idle(d);

    LANE("vk_pipeline");
    optics_gfx_graphics_pipeline *gp = nullptr;
    OT_EXPECT(optics_gfx_graphics_pipeline_create(d, &pd, &gp) == OPTICS_GFX_OK);
    expect_rose(d, SCOPE, "vk_pipeline", OWNER, &before_, "flux_graphics_pipeline_create");
    optics_gfx_graphics_pipeline_release(gp);
    LANE_END("vk_pipeline", "flux_graphics_pipeline");
}

/* ------------------------------------------------------------------ */
/*  Frame-scope enforcement (ADR-0129 decision 4)                     */
/* ------------------------------------------------------------------ */

/* The per-frame drain check is the only drain point that can be enforced
 * continuously without stalling, so it is the one that catches the largest
 * regression class — a per-frame acquire whose release is missing — within a
 * single frame instead of at process exit.
 *
 * A balanced frame-lifetime row must leave the check clean; an unbalanced one
 * must make it report. A check that only ever returned true would be
 * indistinguishable from no check at all, which is why both directions are
 * asserted here. */
static void lane_frame_scope_drain(optics_gfx_device *d) {
    const char *kind = "frame_probe";
    const char *owner = "tests/observe";

    /* Balanced: acquire then release, check is clean. */
    OT_EXPECT(OPTICS_GFX_OBSERVE_ACQUIRE(d, OPTICS_GFX_SCOPE_CONTEXT, OPTICS_GFX_LIFETIME_FRAME,
                                         kind, owner, 0, OPTICS_GFX_SITE_NONE));
    OPTICS_GFX_OBSERVE_RELEASE(d, OPTICS_GFX_SCOPE_CONTEXT, kind, owner, 0);
    OT_EXPECT(optics_gfx_observe_frame_drain_check(d));

    /* Unbalanced: the check must report, and must report at the frame
     * boundary rather than waiting for teardown. */
    OT_EXPECT(OPTICS_GFX_OBSERVE_ACQUIRE(d, OPTICS_GFX_SCOPE_CONTEXT, OPTICS_GFX_LIFETIME_FRAME,
                                         kind, owner, 0, OPTICS_GFX_SITE_NONE));
    OT_EXPECT(!optics_gfx_observe_frame_drain_check(d));

    OPTICS_GFX_OBSERVE_RELEASE(d, OPTICS_GFX_SCOPE_CONTEXT, kind, owner, 0);
    OT_EXPECT(optics_gfx_observe_frame_drain_check(d));
}

/* ------------------------------------------------------------------ */
/*  Bindless double release (ADR-0131)                                */
/* ------------------------------------------------------------------ */

/* A duplicated release used to push the slot a second time, after which two
 * registrations popped the same index and one resource was silently
 * re-pointed at the other. The heap must now refuse it and stay stable. */
static void lane_bindless_double_release(optics_gfx_device *d) {
    uint32_t px[4] = {};
    optics_gfx_image *imgs[3] = {nullptr, nullptr, nullptr};
    optics_gfx_bindless_handle handles[3] = {
        OPTICS_GFX_BINDLESS_INVALID, OPTICS_GFX_BINDLESS_INVALID, OPTICS_GFX_BINDLESS_INVALID};

    for (int i = 0; i < 3; ++i) {
        optics_gfx_image_desc id = OPTICS_GFX_IMAGE_DESC_INIT;
        id.width = 2;
        id.height = 2;
        id.format = OPTICS_GFX_FORMAT_RGBA8_UNORM;
        id.initial_data = px;
        OT_EXPECT(optics_gfx_image_create(d, &id, &imgs[i]) == OPTICS_GFX_OK);
        handles[i] = optics_gfx_image_bindless_handle(imgs[i]);
        OT_EXPECT(handles[i] != OPTICS_GFX_BINDLESS_INVALID);
    }
    /* Three distinct slots: the heap must never hand out an alias. */
    OT_EXPECT(handles[0] != handles[1]);
    OT_EXPECT(handles[1] != handles[2]);
    OT_EXPECT(handles[0] != handles[2]);

    /* Release the middle image, then duplicate its release through the public
     * bindless path. The second call must be refused, not corrupt the stack. */
    optics_gfx_image_release(imgs[1]);
    imgs[1] = nullptr;
    optics_gfx_bindless_release(d, handles[1]); /* duplicate: refused */
    optics_gfx_device_wait_idle(d);

    /* A fourth image must still land on a valid, previously-free slot and not
     * collide with the two live images' slots. */
    optics_gfx_image *fourth = nullptr;
    optics_gfx_image_desc id = OPTICS_GFX_IMAGE_DESC_INIT;
    id.width = 2;
    id.height = 2;
    id.format = OPTICS_GFX_FORMAT_RGBA8_UNORM;
    id.initial_data = px;
    OT_EXPECT(optics_gfx_image_create(d, &id, &fourth) == OPTICS_GFX_OK);
    optics_gfx_bindless_handle h4 = optics_gfx_image_bindless_handle(fourth);
    OT_EXPECT(h4 != handles[0]);
    OT_EXPECT(h4 != handles[2]);

    optics_gfx_image_release(fourth);
    optics_gfx_image_release(imgs[0]);
    optics_gfx_image_release(imgs[2]);
    optics_gfx_device_wait_idle(d);
}

/* ------------------------------------------------------------------ */
/*  Leak visibility: the ledger must actually see a deliberate leak   */
/* ------------------------------------------------------------------ */

/* A detector that cannot fire on a known leak is decoration. This lane
 * deliberately leaks one image and requires the report to name it. */
static void lane_detects_a_real_leak(optics_gfx_device *d) {
    uint32_t px[4] = {};
    optics_gfx_image_desc id = OPTICS_GFX_IMAGE_DESC_INIT;
    id.width = 2;
    id.height = 2;
    id.format = OPTICS_GFX_FORMAT_RGBA8_UNORM;
    id.initial_data = px;

    optics_gfx_observe_entry rows[64] = {};
    optics_gfx_observe_counters before = row_of(d, SCOPE, "vk_memory", OWNER);

    optics_gfx_image *leaked = nullptr;
    OT_EXPECT(optics_gfx_image_create(d, &id, &leaked) == OPTICS_GFX_OK);

    optics_gfx_observe_response resp =
        optics_gfx_observe_report(d, &(optics_gfx_observe_report_opts){
                                         .type = OPTICS_GFX_TYPE_OBSERVE_REPORT_OPTS,
                                         .entries = rows,
                                         .capacity = 64,
                                         .scope = SCOPE,
                                     });
    OT_EXPECT(resp.result == OPTICS_GFX_OK);
    OT_EXPECT(resp.overflowed_kinds == 0);

    bool saw_vk_memory = false;
    for (uint32_t i = 0; i < resp.count; ++i) {
        if (strcmp(rows[i].kind, "vk_memory") == 0) {
            saw_vk_memory = true;
            OT_EXPECT(rows[i].live >= 1);
            OT_EXPECT(rows[i].bytes_live > 0);
            /* A leaking row must carry its creation site: that is the whole
             * difference between this and the old byte-total warning. */
            OT_EXPECT(rows[i].site != nullptr);
        }
    }
    OT_EXPECT(saw_vk_memory);

    optics_gfx_image_release(leaked);
    optics_gfx_device_wait_idle(d);
    expect_drained(d, SCOPE, "vk_memory", OWNER, &before, "deliberate-leak probe (post-release)");
}

int main(void) {
    optics_gfx_device *d = optics_gfx_test_make_headless_device();
    if (!d) {
        fprintf(stderr, "test_resource_leak: no Vulkan device; skipping\n");
        OT_SKIP("no Vulkan device");
    }

    lane_image(d);
    lane_sampler(d);
    lane_buffer(d);
    lane_target(d);
    lane_icc_profile(d);
    lane_graphics_pipeline(d);
    lane_frame_scope_drain(d);
    lane_bindless_double_release(d);
    lane_detects_a_real_leak(d);

    optics_gfx_device_release(d);
    return OT_REPORT();
}
