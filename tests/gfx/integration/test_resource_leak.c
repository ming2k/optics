/* Read one row, treating "never interned" as "zero live" so a kind whose
 * first create is the thing under test does not need pre-warming. */
static optics_gfx_observe_counters row_of(optics_gfx_device *d, optics_gfx_scope scope,
                                          const char *kind, const char *owner) {
    optics_gfx_observe_counters c = {};
    if (optics_gfx_observe_read_counters(
            d, &(optics_gfx_observe_read_counters_opts){
                   .scope = scope, .kind = kind, .owner = owner, .out = &c}) != OPTICS_GFX_OK) {
        c = (optics_gfx_observe_counters){};
    }
    return c;
}

/* Assert that a kind returned to exactly where it started. `what` names the
 * kind in the failure output so a broken run is self-explanatory. */
static void expect_drained(optics_gfx_device *d, optics_gfx_scope scope, const char *kind,
                           const char *owner, const optics_gfx_observe_counters *before,
                           const char *what) {
    optics_gfx_observe_counters after = row_of(d, scope, kind, owner);
    if (after.live != before->live || after.bytes_live != before->bytes_live) {
        fprintf(stderr,
                "FAIL %s: %s leaked — live %llu -> %llu, bytes %llu -> %llu "
                "(acquire_total=%llu release_total=%llu)\n",
                __FILE__, what, (unsigned long long)before->live, (unsigned long long)after.live,
                (unsigned long long)before->bytes_live, (unsigned long long)after.bytes_live,
                (unsigned long long)after.acquire_total, (unsigned long long)after.release_total);
        OT_MANUAL_FAIL();
    }
    OT_MANUAL_CHECK();
}

static void expect_rose(optics_gfx_device *d, optics_gfx_scope scope, const char *kind,
                        const char *owner, const optics_gfx_observe_counters *before,
                        const char *what) {
    optics_gfx_observe_counters after = row_of(d, scope, kind, owner);
    if (after.live <= before->live) {
        fprintf(stderr, "FAIL %s: %s did not register in the ledger (live %llu -> %llu)\n",
                __FILE__, what, (unsigned long long)before->live, (unsigned long long)after.live);
        OT_MANUAL_FAIL();
    }
    OT_MANUAL_CHECK();
}

/* Every kind shares the device scope and the flux/core owner unless stated. */
#define SCOPE OPTICS_GFX_SCOPE_DEVICE
#define OWNER "flux/core"

/* Exact deltas are measured between two *identical* iterations, the first of
 * which is a warm-up. That is not a tolerance: pool blocks, staging entries
 * and cached pipeline state legitimately grow once and then stay resident, and
 * counting that one-time growth as a leak would force a tolerance back in.
 * A leak is defined here as "the second iteration did not return the ledger to
 * where the first one left it", which is exact. */
#define LANE(kind_)                                                                                \
    optics_gfx_observe_counters before_ = row_of(d, SCOPE, (kind_), OWNER);                        \
    optics_gfx_device_wait_idle(d)

#define LANE_END(kind_, what_)                                                                     \
    optics_gfx_device_wait_idle(d);                                                                \
    expect_drained(d, SCOPE, (kind_), OWNER, &before_, (what_))

static void make_image(optics_gfx_device *d, uint32_t w, uint32_t h, optics_gfx_image **out) {
    uint32_t px[64 * 64];
    memset(px, 0x5a, sizeof px);
    optics_gfx_image_desc id = OPTICS_GFX_IMAGE_DESC_INIT;
    id.width = w;
    id.height = h;
    id.format = OPTICS_GFX_FORMAT_RGBA8_UNORM;
    id.initial_data = px;
    *out = nullptr;
    OT_EXPECT(optics_gfx_image_create(d, &id, out) == OPTICS_GFX_OK);
}

static void drop_image(optics_gfx_device *d, optics_gfx_image *im) {
    optics_gfx_image_release(im);
    optics_gfx_device_wait_idle(d);
}

static void lane_image(optics_gfx_device *d) {
    optics_gfx_image *warm = nullptr;
    make_image(d, 8, 8, &warm);
    drop_image(d, warm); /* warm-up: absorb pool/staging one-time growth */

    LANE("vk_image");
    optics_gfx_observe_counters bindless_before = row_of(d, SCOPE, "bindless", OWNER);
    optics_gfx_observe_counters mem_before = row_of(d, SCOPE, "vk_memory", OWNER);

    optics_gfx_image *img = nullptr;
    make_image(d, 8, 8, &img);
    expect_rose(d, SCOPE, "vk_image", OWNER, &before_, "flux_image_create");
    drop_image(d, img);

    LANE_END("vk_image", "flux_image");
    expect_drained(d, SCOPE, "bindless", OWNER, &bindless_before, "flux_image bindless slot");
    expect_drained(d, SCOPE, "vk_memory", OWNER, &mem_before, "flux_image device memory");
}

static void lane_sampler(optics_gfx_device *d) {
    optics_gfx_sampler_desc sd = OPTICS_GFX_SAMPLER_DESC_INIT;
    sd.min_filter = OPTICS_GFX_FILTER_LINEAR;
    sd.mag_filter = OPTICS_GFX_FILTER_LINEAR;
    sd.mipmap_mode = OPTICS_GFX_FILTER_LINEAR;
    sd.address_u = OPTICS_GFX_ADDRESS_REPEAT;
    sd.address_v = OPTICS_GFX_ADDRESS_REPEAT;
    sd.address_w = OPTICS_GFX_ADDRESS_REPEAT;

    optics_gfx_sampler *warm = nullptr;
    OT_EXPECT(optics_gfx_sampler_create(d, &sd, &warm) == OPTICS_GFX_OK);
    optics_gfx_sampler_release(warm);
    optics_gfx_device_wait_idle(d);

    LANE("vk_sampler");
    optics_gfx_sampler *s = nullptr;
    OT_EXPECT(optics_gfx_sampler_create(d, &sd, &s) == OPTICS_GFX_OK);
    expect_rose(d, SCOPE, "vk_sampler", OWNER, &before_, "flux_sampler_create");
    optics_gfx_sampler_release(s);
    LANE_END("vk_sampler", "flux_sampler");
}

static void lane_buffer(optics_gfx_device *d) {
    optics_gfx_buffer_desc bd = OPTICS_GFX_BUFFER_DESC_INIT;
    bd.size = 4096;
    bd.usage = OPTICS_GFX_BUFFER_USAGE_STORAGE;
    bd.location = OPTICS_GFX_BUFFER_HOST_VISIBLE;
    bd.device_address = true;

    optics_gfx_buffer *warm = nullptr;
    OT_EXPECT(optics_gfx_buffer_create(d, &bd, &warm) == OPTICS_GFX_OK);
    optics_gfx_buffer_release(warm);
    optics_gfx_device_wait_idle(d);

    LANE("vk_buffer");
    optics_gfx_observe_counters mem_before = row_of(d, SCOPE, "vk_memory", OWNER);
    optics_gfx_buffer *b = nullptr;
    OT_EXPECT(optics_gfx_buffer_create(d, &bd, &b) == OPTICS_GFX_OK);
    expect_rose(d, SCOPE, "vk_buffer", OWNER, &before_, "flux_buffer_create");
    optics_gfx_buffer_release(b);
    LANE_END("vk_buffer", "flux_buffer");
    expect_drained(d, SCOPE, "vk_memory", OWNER, &mem_before, "flux_buffer device memory");
}

static void lane_target(optics_gfx_device *d) {
    optics_gfx_target_desc td = OPTICS_GFX_TARGET_DESC_INIT;
    td.usage = OPTICS_GFX_TARGET_COLOR;
    td.format = OPTICS_GFX_FORMAT_RGBA8_UNORM;
    td.width = 32;
    td.height = 32;

    optics_gfx_target *warm = nullptr;
    if (optics_gfx_target_create(d, &td, &warm) != OPTICS_GFX_OK) {
        fprintf(stderr, "note: flux_target_create unavailable; lane skipped\n");
        return;
    }
    optics_gfx_target_release(warm);
    optics_gfx_device_wait_idle(d);

    LANE("vk_target");
    optics_gfx_target *t = nullptr;
    OT_EXPECT(optics_gfx_target_create(d, &td, &t) == OPTICS_GFX_OK);
    expect_rose(d, SCOPE, "vk_target", OWNER, &before_, "flux_target_create");
    optics_gfx_target_release(t);
    LANE_END("vk_target", "flux_target");
}

static void lane_icc_profile(optics_gfx_device *d) {
    /* Device-free profile parsing: a valid profile allocates a host wrapper
     * that must be released. A rejected body allocates nothing. Both paths
     * must leave the host row exactly where it started. */
    LANE("host");
    optics_gfx_icc_profile *p = nullptr;
    (void)optics_gfx_icc_profile_create("not-a-profile", 13, &p);
    if (p)
        optics_gfx_icc_profile_release(p);
    LANE_END("host", "flux_icc_profile");
}

