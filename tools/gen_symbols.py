#!/usr/bin/env python3
"""Generate docs/reference/symbols.md from the public headers.

The symbol reference used to be maintained by hand and drifted until every row
named a function that no longer existed. It is now derived: every exported
function of every library (`OPTICS_<MOD>_API`; motion's expands to
`static inline`), grouped by library and header, with the first
sentence of the comment directly above its declaration.

Usage:
  tools/gen_symbols.py            rewrite docs/reference/symbols.md
  tools/gen_symbols.py --check    fail if the committed file is stale (lint suite)
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "reference" / "symbols.md"

LIBRARIES = [
    ("gfx", "rendering foundation: RHI, canvas, scene draw core, compute, effects"),
    ("text", "text shaping, layout and glyph runs"),
    ("svg", "SVG document compiler"),
    ("scene", "3D scene graph and glTF loading"),
    ("material", "surface materials"),
    ("motion", "springs and easing (header-only)"),
    ("window", "native window, event pump and platform services"),
    ("ui", "immediate-mode UI engine"),
    ("app", "application shell"),
]

HEADER = """# Symbol Reference

<!-- Generated by tools/gen_symbols.py from the public headers. Do not edit by
     hand: run the script after changing a public declaration. The lint suite
     fails when this file is stale. -->

Every exported function, grouped by library and public header, with the first
sentence of its header comment. The headers remain the authoritative contract.
For the shape of the API (object model, lifecycle, error model), see
[API Reference](api.md); for blocking behavior per call, see
[Thread Safety](thread-safety.md).
"""

COMMENT_RE = re.compile(r"/\*.*?\*/|//[^\n]*", re.DOTALL)
ATTR_RE = re.compile(r"(?:\[\[[a-z_]+(?:\([^)]*\))?\]\]|OPTICS_[A-Z]+_NODISCARD|static|inline)\s*$")


def blank_comments(text: str) -> str:
    """Comments replaced by spaces of equal length, so offsets still line up."""
    return COMMENT_RE.sub(lambda m: re.sub(r"[^\n]", " ", m.group(0)), text)


def doc_before(text: str, pos: int) -> str:
    """First sentence of the comment ending right before `pos`, skipping
    attributes between the comment and the declaration."""
    head = text[:pos].rstrip()
    while True:
        m = ATTR_RE.search(head)
        if not m:
            break
        head = head[: m.start()].rstrip()
    if head.endswith("*/"):
        start = head.rfind("/*")
        # Only a comment on its own line documents what follows; a trailing
        # comment belongs to the previous line's declaration.
        if head[head.rfind("\n", 0, start) + 1 : start].strip():
            return ""
        body = head[start + 2 : -2]
    else:
        lines = []
        for line in reversed(head.splitlines()):
            s = line.strip()
            if not s.startswith("//"):
                break
            lines.append(s[2:])
        if not lines:
            return ""
        body = " ".join(reversed(lines))
    body = re.sub(r"^\s*\*\s?", " ", body, flags=re.MULTILINE)
    body = " ".join(body.split())
    if body.startswith("=") or body.startswith("-"):  # a section banner, not a doc comment
        return ""
    m = re.search(r"(?<!e\.g)(?<!i\.e)\.(?:\s|$)", body)
    sentence = body[: m.start() + 1] if m else body
    return sentence.replace("|", "\\|")


def symbols(mod: str, header: Path) -> list[tuple[str, str]]:
    text = header.read_text(encoding="utf-8")
    code = blank_comments(text)
    decl = re.compile(rf"\bOPTICS_{mod.upper()}_API\b[^;{{]*?\b(optics_{mod}_[a-z0-9_]+)\s*\(")
    out, seen = [], set()
    for m in decl.finditer(code):
        name = m.group(1)
        if name in seen:
            continue
        seen.add(name)
        # The doc comment precedes the start of the declaration's line.
        line_start = text.rfind("\n", 0, m.start()) + 1
        out.append((name, doc_before(text, line_start)))
    return out


def render() -> str:
    parts = [HEADER]
    for mod, title in LIBRARIES:
        inc = ROOT / "libs" / mod / "include" / "optics"
        if not inc.is_dir():
            continue
        entry = inc / f"{mod}.h"
        headers = [entry] if entry.is_file() else []
        headers += sorted(p for p in (inc / mod).rglob("*.h")) if (inc / mod).is_dir() else []
        sections = []
        for h in headers:
            rows = symbols(mod, h)
            if not rows:
                continue
            rel = h.relative_to(ROOT / "libs" / mod / "include").as_posix()
            lines = [f"### `<{rel}>`", "", "| Symbol | Description |", "|--------|-------------|"]
            lines += [f"| `{name}` | {doc} |" for name, doc in rows]
            sections.append("\n".join(lines))
        if sections:
            parts.append(f"## {mod} — {title}\n\n" + "\n\n".join(sections))
    return "\n\n".join(parts) + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv[1:]:
        current = OUT.read_text(encoding="utf-8") if OUT.is_file() else ""
        if current != text:
            sys.stderr.write(
                "docs/reference/symbols.md is stale: run tools/gen_symbols.py and commit the result\n"
            )
            return 1
        print("symbol reference up to date")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
